"""Camera registry: load the committed camera manifest.

The manifest (``cctv/data/cameras_lie.json``) is generated by
``python -m cctv.recon.build_manifest`` from a saved snapshot of the official
511NY camera list. Everything else (pipeline, web app) reads cameras from here.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

PACKAGE_DIR = Path(__file__).resolve().parent
DATA_DIR = PACKAGE_DIR / "data"
MANIFEST_PATH = DATA_DIR / "cameras_lie.json"
CALIBRATION_DIR = DATA_DIR / "calibration"


def load_manifest(path: Path | str = MANIFEST_PATH) -> dict[str, Any]:
    """Return the whole manifest dict (``cameras`` list plus metadata)."""
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def load_cameras(path: Path | str = MANIFEST_PATH) -> list[dict[str, Any]]:
    return load_manifest(path)["cameras"]


def get_camera(camera_id: str, path: Path | str = MANIFEST_PATH) -> dict[str, Any]:
    for cam in load_cameras(path):
        if cam["id"] == camera_id:
            return cam
    raise KeyError(f"camera {camera_id!r} not in manifest {path}")


def calibration_path(camera_id: str, view_id: str | None = None) -> Path:
    """Calibration JSON of one view, or of the camera's primary (first calibrated) view.

    Falls back to the round-1 flat path ``<CAM>.json`` (which may not exist) so
    callers can keep using ``Path.exists()``.
    """
    from cctv.views import get_view, primary_view

    view = get_view(camera_id, view_id) if view_id else primary_view(camera_id)
    if view is not None and view.calibration_path is not None:
        return view.calibration_path
    return CALIBRATION_DIR / f"{camera_id}.json"
